#!/usr/bin/env python3
"""Build web/captions.js from the whisper word timings: ONE word at a time, frame-timed (30 fps).
First word is shown in caps ("STOP"); every other word keeps its natural case, trailing , . ; : removed.
   python3 make_captions.py"""
import json, re
CTA_OFFSET = 21.70775  # call_to_action.mp3 starts where audio_head_touch.mp3 ends (see voice.wav)
TOTAL = 888
words = list(json.load(open("audio_head_touch.mp3.words.json")))
words += [dict(w, s=w["s"] + CTA_OFFSET, e=w["e"] + CTA_OFFSET) for w in json.load(open("call_to_action.mp3.words.json"))]
out = []
for i, w in enumerate(words):
    t = re.sub(r"[.,;:]+$", "", w["w"]).replace("’", "'")
    if i == 0: t = t.upper()
    a = max(0, round(w["s"] * 30) - 1)                       # lands 1 frame before the word
    e = round(w["e"] * 30)
    nxt = round(words[i + 1]["s"] * 30) - 1 if i + 1 < len(words) else TOTAL
    b = nxt if nxt - e <= 12 else e + 8                       # hold to the next word, clear during long pauses
    out.append({"a": a, "b": min(b, TOTAL), "t": t})
# a word that would flash for under 3 frames joins the next one ("The reason", "and I'll")
k = 0
while k < len(out) - 1:
    if out[k]["b"] - out[k]["a"] < 3: out[k + 1] = {"a": out[k]["a"], "b": out[k + 1]["b"], "t": out[k]["t"] + " " + out[k + 1]["t"]}; out.pop(k)
    else: k += 1
open("web/captions.js", "w").write("// generated by make_captions.py - do not edit by hand\nexport const CAPTIONS = " + json.dumps(out) + ";\n")
for c in out: print(f"{c['a']:4d}-{c['b']:4d}  {c['t']}")
